-- JOB RELATED TABLE


CREATE TABLE JOB(
    JOB_ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ORDER_LINE_ID INT constraint fk_ORDER_LINE_id_in_JOB REFERENCES OREDER_LINE(ORDER_LINE_ID),
    OPS_MANAGER_ID INT constraint fk_OPS_MNG_id_in_JOB REFERENCES OPERATION_MANAGER(EMPLOYEE_ID),
    PRINT_PRODUCER_ID INT constraint fk_PRINT_PRODUCER_id_in_JOB REFERENCES PRINT_PRODUCER(EMPLOYEE_ID),
    INSTALLER_ID INT constraint fk_INSTALLATION_WORKER_id_JOB REFERENCES INSTALLATION_WORKER(EMPLOYEE_ID),
    JOB_TYPE varchar2(20) DEFAULT 'PRINT' CONSTRAINT job_type check (JOB_TYPE IN ('PRINT','INSTALL','PRINT_INSTALL')),
    PRINT_STATUS varchar2(15) DEFAULT 'NOT_REQUIRED' CONSTRAINT print_status check (PRINT_STATUS IN ('NOT_REQUIRED','PENDING','IN_PROGRESS','OUTSOURCED','COMPLETED')),
    INSTALL_STATUS varchar2(15) DEFAULT 'NOT_REQUIRED' CONSTRAINT install_status check (INSTALL_STATUS IN ('NOT_REQUIRED','PENDING','SCHEDULED','COMPLETED')),
    START_DATE DATE DEFAULT SYSDATE NOT NULL,
    DUE_DATE DATE DEFAULT SYSDATE NOT NULL,
    PRINT_COMPLETED_DATE DATE DEFAULT SYSDATE NOT NULL,
    INSTALLER_ASSIGNED_DATE DATE DEFAULT SYSDATE NOT NULL,
    COMPLETED_DATE DATE DEFAULT SYSDATE NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL
);


