Create table Address(
    ADDRESS_ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    LINE_1 varchar2(100) Not NULL,
    Line_2 varchar2(100) NULL,
    CITY varchar2(20) NOT NULL,
    PROVINCE varchar2(20) not NULL,
    POSTAL_CODE varchar2(6) NOT NULL,
    COUNTRY varchar2(20) DEFAULT 'Canada' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL
);

-- COMPANY's EMPLOYEE ROLES TABLES
Create table EMPLOYEE(
    EMPLOYEE_ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ADDRESS_ID INT constraint fk_address_id_in_employee REFERENCES Address(ADDRESS_ID),
    NAME varchar2(100) Not NULL,
    ROLE varchar2(10) NOT NULL CHECK(ROLE IN ('SALES','OPERATIONS','PRINT','INSTALL','INVENTORY','ADMIN')),
    PHONE varchar2(10) NOT NULL,
    EMAIL varchar2(100)
    constraint employee_email UNIQUE 
    CONSTRAINT chk_valid_email_employee CHECK (
        REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')
    )
,
    HIRE_DATE date NOT NULL,
    IS_ACTIVE CHAR(1) DEFAULT 'Y' CONSTRAINT is_active_employee CHECK (IS_ACTIVE IN ('Y','N')),
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT DATE DEFAULT SYSDATE NOT NULL
);

